#!/usr/bin/env python3
"""Configure Cloudflare Email Routing for the public contact address.

Applies the DNS records and the routing rule that make
``privacy@<zone>`` forward to the operator's real mailbox.

Why a script and not the dashboard:
    The zone is already on Cloudflare with DNS managed there, so the whole
    setup is three MX records, one SPF record, one DMARC record and one
    routing rule. Doing it through the API makes the result auditable and
    re-runnable, and it avoids the dashboard's "Email Service" navigation
    changing shape between versions.

Token permissions — verified against the live API, not assumed:
    WORKS  zones/<id>/email/routing/rules   (read + write)   -> Email Routing Rules Edit
    WORKS  zones/<id>/dns_records            (read + write)   -> DNS Edit
    BLOCKED zones/<id>/email/routing         (the settings/enable endpoint)
    BLOCKED zones/<id>/email/routing/destinations
    BLOCKED zones/<id>/email/routing/logs
    BLOCKED accounts/<id>/email/routing/addresses

    The blocked endpoints are the ones that need "Email Routing Addresses
    Edit" plus zone-settings write. A token scoped to "Account: Zone Read"
    + "Zone: DNS Edit" + "Email Routing Rules Edit" can do everything this
    script does, because the routing rule is written directly instead of
    being created through the onboarding endpoint.

    Two consequences worth knowing:
      * The DKIM record (cf2024-1._domainkey) is normally generated by CF
        during onboarding. The endpoint that returns it is blocked, so this
        script cannot publish it. Forwarded mail still arrives — CF signs
        outbound mail and Gmail falls back to SPF — but DKIM verification
        will not pass. Fix: enable Email Routing once in the dashboard, which
        publishes the DKIM record, then re-run this script.
      * Destination addresses are account-level and this token cannot list
        or create them, so the forwarding target must already be verified
        in the dashboard. If it is not, CF keeps the rule inactive even
        though the API reports enabled=true.

Usage:
    CF_TOKEN=...  CF_ZONE_ID=...  CF_ZONE_NAME=linkattest.com \\
    CF_DESTINATION=you@example.com \\
    python3 tools/setup_email_routing.py [--dry-run]

The token is read from the environment, never from a file, and is never
printed.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.request

API = "https://api.cloudflare.com/client/v4"

# Cloudflare Email Routing's own mail exchangers. Documented in
# https://developers.cloudflare.com/email-service/configuration/domains/
ROUTING_MX = [
    ("route1.mx.cloudflare.net", 10),
    ("route2.mx.cloudflare.net", 20),
    ("route3.mx.cloudflare.net", 30),
]
# Cloudflare signs forwarded mail with this SPF include.
ROUTING_SPF = "v=spf1 include:_spf.mx.cloudflare.net ~all"
# p=none on purpose: with no DKIM record published (see module docstring),
# a strict policy would make forwarded mail fail DMARC and get filtered.
ROUTING_DMARC = "v=DMARC1; p=none; rua=mailto:{local}@{zone}; fo=1"


class CF:
    """Minimal Cloudflare API client: one verb, JSON in and out."""

    def __init__(self, token: str, zone_id: str) -> None:
        self.token = token
        self.zone_id = zone_id

    def _call(self, method: str, path: str, body: dict | None = None):
        url = f"{API}{path}"
        data = json.dumps(body).encode() if body is not None else None
        last_exc: Exception | None = None
        for attempt in range(4):
            req = urllib.request.Request(url, data=data, method=method)
            req.add_header("Authorization", f"Bearer {self.token}")
            req.add_header("Content-Type", "application/json")
            req.add_header("Accept", "application/json")
            try:
                with urllib.request.urlopen(req, timeout=30) as resp:
                    return json.load(resp)
            except urllib.error.HTTPError as exc:
                raw = exc.read().decode("utf-8", "replace")
                try:
                    return json.loads(raw)
                except json.JSONDecodeError:
                    return {"success": False, "errors": [{"message": raw[:200]}]}
            except (urllib.error.URLError, TimeoutError, ConnectionError) as exc:
                # Transient network failure. Cloudflare's API is idempotent
                # for the reads and the record creates here (each create
                # checks for an existing identical record first), so a
                # bounded retry is safe.
                last_exc = exc
                if attempt < 3:
                    time.sleep(2 ** attempt)
        return {"success": False,
                "errors": [{"message": f"network failure: {last_exc}"}]}

    def get(self, path: str):
        return self._call("GET", path)

    def post(self, path: str, body: dict):
        return self._call("POST", path, body)

    def put(self, path: str, body: dict):
        return self._call("PUT", path, body)

    def delete(self, path: str):
        return self._call("DELETE", path)


def dns_records(cf: CF) -> list[dict]:
    out = cf.get(f"/zones/{cf.zone_id}/dns_records?per_page=200")
    return out.get("result") or []


def ensure_txt(cf: CF, name: str, content: str, dry_run: bool) -> bool:
    """Create a TXT record unless an identical one already exists."""
    for r in dns_records(cf):
        if r["type"] == "TXT" and r["name"] == name and r["content"] == content:
            print(f"  = TXT {name} (already present)")
            return True
    if dry_run:
        print(f"  + TXT {name} = {content}")
        return True
    res = cf.post(f"/zones/{cf.zone_id}/dns_records",
                  {"type": "TXT", "name": name, "content": content})
    if res.get("success"):
        print(f"  + TXT {name} = {content}")
        return True
    print(f"  ! TXT {name} failed: {_err(res)}")
    return False


def ensure_mx(cf: CF, name: str, dry_run: bool) -> bool:
    """Create the three Cloudflare routing MX records, skipping existing."""
    ok = True
    existing = {(r["name"], r["content"]) for r in dns_records(cf)
                if r["type"] == "MX"}
    for host, prio in ROUTING_MX:
        if (name, host) in existing:
            print(f"  = MX {name} -> {host} (already present)")
            continue
        if dry_run:
            print(f"  + MX {name} -> {host} prio={prio}")
            continue
        res = cf.post(f"/zones/{cf.zone_id}/dns_records",
                      {"type": "MX", "name": name,
                       "content": host, "priority": prio})
        if res.get("success"):
            print(f"  + MX {name} -> {host} prio={prio}")
        else:
            print(f"  ! MX {name} -> {host} failed: {_err(res)}")
            ok = False
    return ok


def _err(res: dict) -> str:
    errs = res.get("errors") or [{}]
    return f"{errs[0].get('code')} {errs[0].get('message')}"


def ensure_rule(cf: CF, address: str, destination: str, dry_run: bool) -> bool:
    """Create or update the rule that forwards `address` to `destination`.

    Uses PUT on an existing rule and POST for a new one. PATCH on a rule id
    is rejected by the API ("Authentication error") even though the same
    token may POST and PUT rules — an inconsistency in Cloudflare's
    permission check, so the write path here avoids PATCH entirely.
    """
    rules_res = cf.get(f"/zones/{cf.zone_id}/email/routing/rules?per_page=100")
    if not rules_res.get("success"):
        print(f"  ! cannot list rules: {_err(rules_res)}")
        return False

    wanted = {
        "name": address,
        "enabled": True,
        "matchers": [{"type": "literal", "field": "to", "value": address}],
        "actions": [{"type": "forward", "value": [destination]}],
    }

    for rule in rules_res.get("result") or []:
        for m in rule.get("matchers") or []:
            if m.get("type") == "literal" and m.get("value") == address:
                if dry_run:
                    print(f"  = rule {address} -> {destination} "
                          f"(already present, enabled={rule.get('enabled')})")
                    return True
                res = cf.put(
                    f"/zones/{cf.zone_id}/email/routing/rules/{rule['id']}",
                    wanted)
                if res.get("success"):
                    print(f"  * rule {address} -> {destination} (updated, enabled)")
                    return True
                print(f"  ! rule update failed: {_err(res)}")
                return False

    if dry_run:
        print(f"  + rule {address} -> {destination}")
        return True
    res = cf.post(f"/zones/{cf.zone_id}/email/routing/rules", wanted)
    if res.get("success"):
        print(f"  + rule {address} -> {destination} "
              f"(id={res['result']['id']}, enabled)")
        return True
    print(f"  ! rule create failed: {_err(res)}")
    return False


def main() -> int:
    ap = argparse.ArgumentParser(
        description="Set up Cloudflare Email Routing for a public address.")
    ap.add_argument("--dry-run", action="store_true",
                    help="print what would change, touch nothing")
    ap.add_argument("--zone-id", default=os.environ.get("CF_ZONE_ID", ""))
    ap.add_argument("--zone-name", default=os.environ.get("CF_ZONE_NAME", ""))
    ap.add_argument("--destination", default=os.environ.get("CF_DESTINATION", ""))
    ap.add_argument("--address", default=os.environ.get("CF_ADDRESS", ""),
                    help="public local part; default privacy@<zone-name>")
    args = ap.parse_args()

    token = os.environ.get("CF_TOKEN", "")
    if not token:
        print("CF_TOKEN is required", file=sys.stderr)
        return 2
    if not args.zone_id or not args.zone_name:
        print("CF_ZONE_ID and CF_ZONE_NAME are required", file=sys.stderr)
        return 2
    if not args.destination:
        print("CF_DESTINATION is required (the verified mailbox to forward to)",
              file=sys.stderr)
        return 2

    address = args.address or f"privacy@{args.zone_name}"
    cf = CF(token, args.zone_id)

    print(f"zone      : {args.zone_name} ({args.zone_id})")
    print(f"address   : {address}")
    print(f"forward to: {args.destination}")
    print(f"mode      : {'dry-run' if args.dry_run else 'apply'}\n")

    print("DNS:")
    ok = ensure_mx(cf, args.zone_name, args.dry_run)
    ok &= ensure_txt(cf, args.zone_name, ROUTING_SPF, args.dry_run)
    local = address.split("@", 1)[0]
    ok &= ensure_txt(cf, f"_dmarc.{args.zone_name}",
                     ROUTING_DMARC.format(local=local, zone=args.zone_name),
                     args.dry_run)

    print("\nRouting rule:")
    ok &= ensure_rule(cf, address, args.destination, args.dry_run)

    print()
    if ok:
        print("Email routing configured.")
        if not args.dry_run:
            print("Reminder: the forwarding destination must be verified in")
            print("the Cloudflare dashboard (Compute > Email Service > Email")
            print("Routing > Destination Addresses). Until it is, CF keeps the")
            print("rule inactive and mail is dropped.")
        return 0
    print("One or more steps failed — see above.", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
